import unittest

from codejig.install import is_generated, prune_rules, rule_files, run, stamp
from codejig.overlay import Overlay
from tests.util import tree, write

RULE = 'prefix_rule(pattern = ["make", "test"], decision = "allow")\n'


def setup(root):
    core = root / "core-repo"
    write(core / "core" / "AGENTS.core.md", "core rules\n")
    write(core / "core" / "tiers.toml", 'default = "medium"\n')
    ov = root / "overlay"
    write(ov / "profiles.toml", 'default = "m"\n')
    return core, Overlay(ov, "v0.2.0", True), root / "codex home"


class Rules(unittest.TestCase):
    def test_no_rules_dir(self):
        self.assertEqual(rule_files(tree(self)), {})

    def test_names_and_marker(self):
        ov = tree(self)
        write(ov / "rules" / "toolchain.rules", RULE)
        files = rule_files(ov)
        self.assertEqual(list(files), ["code-jig-toolchain.rules"])
        self.assertTrue(files["code-jig-toolchain.rules"].startswith("# generated by code-jig"))

    def test_install_writes_and_prunes(self):
        core, ov, home = setup(tree(self))
        write(ov.root / "rules" / "a.rules", RULE)
        write(ov.root / "rules" / "b.rules", RULE)
        run(core, ov, home)
        (ov.root / "rules" / "b.rules").unlink()
        lines = run(core, ov, home)
        self.assertTrue(is_generated(home / "rules" / "code-jig-a.rules"))
        self.assertFalse((home / "rules" / "code-jig-b.rules").exists())
        self.assertTrue(any("removed" in line for line in lines))

    def test_hand_edited_generated_rule_is_left_with_warning(self):
        rules_dir = tree(self) / "rules"
        f = write(rules_dir / "code-jig-old.rules", stamp(RULE, "hash") + "# mine\n")
        lines = prune_rules(rules_dir, set())
        self.assertTrue(f.exists())
        self.assertTrue(any(line.startswith("warning:") and "code-jig-old.rules" in line for line in lines))

    def test_default_rules_and_user_files_untouched(self):
        core, ov, home = setup(tree(self))
        d = write(home / "rules" / "default.rules", RULE)
        u = write(home / "rules" / "mine.rules", RULE)
        run(core, ov, home)
        self.assertEqual(d.read_text(encoding="utf-8"), RULE)
        self.assertEqual(u.read_text(encoding="utf-8"), RULE)
