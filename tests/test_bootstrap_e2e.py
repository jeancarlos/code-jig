ROOT = Path(__file__).resolve().parent.parent
TAG = f"v{VERSION}"
SOURCE = (ROOT / "bootstrap.py").read_text(encoding="ascii")


class Quiet(http.server.SimpleHTTPRequestHandler):
    def log_message(self, *args):
        self.server.paths.append(self.path)


@unittest.skipUnless((ROOT / ".git").exists(), "needs a git checkout")
class EndToEnd(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.srv = Path(tempfile.mkdtemp())
        env = dict(os.environ, PYTHONPATH=str(ROOT))
        subprocess.run([sys.executable, str(ROOT / ".github" / "scripts" / "build_release.py"), TAG,
                        str(cls.srv / "v" / TAG)], env=env, check=True, capture_output=True)
        cls.httpd = http.server.ThreadingHTTPServer(("127.0.0.1", 0), functools.partial(Quiet, directory=str(cls.srv)))
        cls.httpd.paths = []
        threading.Thread(target=cls.httpd.serve_forever, daemon=True).start()
        cls.base = f"http://127.0.0.1:{cls.httpd.server_address[1]}"

    @classmethod
    def tearDownClass(cls):
        cls.httpd.shutdown()
        cls.httpd.server_close()
        shutil.rmtree(cls.srv, True)

    def setUp(self):
        self.root = tree(self)
        self.home = self.root / "home"
        self.home.mkdir()
        self.env = {k: v for k, v in os.environ.items() if k not in ("CODE_JIG_OVERLAY", "PYTHONPATH", "CODEX_HOME")}
        self.env.update(HOME=str(self.home), USERPROFILE=str(self.home), GIT_CONFIG_GLOBAL=str(self.root / "gitconfig"),
                        CODE_JIG_SKILLS_DIR=str(self.root / "skills"), CODEX_BIN=str(self.root / "no-codex"))
        self.dirs = dict(data=self.root / "data", bins=self.root / "bin", overlay=self.root / "code-jig-overlay",
                         codex=self.root / "codex home")
        self.httpd.paths.clear()

    def run_bootstrap(self, *extra):
        cmd = [sys.executable, "-I", str(ROOT / "bootstrap.py"), "--base-url", self.base, "--repo", "invalid/none",
               "--data-dir", str(self.dirs["data"]), "--bin-dir", str(self.dirs["bins"]),
               "--overlay-dir", str(self.dirs["overlay"]), "--codex-home", str(self.dirs["codex"]), *extra]
        return subprocess.run(cmd, env=self.env, capture_output=True, text=True, errors="replace", timeout=300)

    def test_fresh_install_writes_everything(self):
        done = self.run_bootstrap("--version", TAG)
        self.assertEqual(done.returncode, 0, done.stderr)
        self.assertTrue(done.stdout.startswith("code-jig bootstrap"))
        core = self.dirs["data"] / TAG
        bootstrap.verify_tree(core, TAG)
        self.assertTrue(bootstrap.owned(self.dirs["overlay"]))
        self.assertEqual(bootstrap.read_pin(self.dirs["overlay"]), TAG)
        launcher = bootstrap.launcher_paths(self.dirs["bins"])[0]
        self.assertIn(bootstrap.MARK + TAG, launcher.read_text(encoding="utf-8"))
        agents = (self.dirs["codex"] / "AGENTS.md").read_text(encoding="utf-8")
        self.assertTrue(agents.startswith("<!-- generated by code-jig"))
        self.assertIn(f"/v/{TAG}/code-jig.zip", self.httpd.paths)
        self.assertFalse(any("?" in p for p in self.httpd.paths))

    def test_rerun_after_running_code_jig_reuses_the_folder(self):
        self.assertEqual(self.run_bootstrap("--version", TAG).returncode, 0)
        launcher = bootstrap.launcher_paths(self.dirs["bins"])[0]
        subprocess.run([str(launcher), "--help"], env=self.env, capture_output=True)
        self.httpd.paths.clear()
        done = self.run_bootstrap()
        self.assertEqual(done.returncode, 0, done.stderr)
        self.assertIn("reusing", done.stdout)
        self.assertEqual(self.httpd.paths, [])

    def test_tampered_folder_refused(self):
        self.assertEqual(self.run_bootstrap("--version", TAG).returncode, 0)
        write(self.dirs["data"] / TAG / "README.md", "evil\n")
        done = self.run_bootstrap()
        self.assertEqual(done.returncode, 1)
        self.assertIn("delete it and rerun", done.stderr)

    def test_foreign_launcher_refused_before_install(self):
        write(bootstrap.launcher_paths(self.dirs["bins"])[0], "#!/bin/sh\necho mine\n")
        done = self.run_bootstrap("--version", TAG)
        self.assertEqual(done.returncode, 1)
        self.assertFalse((self.dirs["codex"] / "AGENTS.md").exists())
        self.assertFalse(self.dirs["data"].exists())

    def test_install_failure_keeps_the_old_launcher(self):
        self.assertEqual(self.run_bootstrap("--version", TAG).returncode, 0)
        launcher = bootstrap.launcher_paths(self.dirs["bins"])[0]
        launcher.write_text(bootstrap.MARK + "old\n", encoding="utf-8")
        before = launcher.read_bytes()
        write(self.dirs["overlay"] / "profiles.toml", "not = [valid\n")
        done = self.run_bootstrap()
        self.assertNotEqual(done.returncode, 0)
        self.assertEqual(launcher.read_bytes(), before)

    def test_foreign_overlay_with_other_version_refused(self):
        write(self.dirs["overlay"] / "overlay.toml", 'core_version = "v0.0.1"\ncore_writable = false\n')
        done = self.run_bootstrap("--version", TAG)
        self.assertEqual(done.returncode, 1)
        self.assertIn("bump core_version", done.stderr)

    def test_missing_version_says_no_zip(self):
        done = self.run_bootstrap("--version", "v0.0.1")
        self.assertEqual(done.returncode, 1)
        self.assertIn("before v0.11.0", done.stderr)


class PipeShape(unittest.TestCase):
    def test_isolated_mode_ignores_a_planted_module(self):
        cwd = tree(self)
        marker = cwd / "planted"
        write(cwd / "argparse.py", f"open({str(marker)!r}, 'w').close()\nfrom importlib import import_module\n")
        for flags, planted in (([], True), (["-I"], False)):
            with self.subTest(flags=flags):
                if marker.exists():
                    marker.unlink()
                subprocess.run([sys.executable, *flags, "-", "--help"], input=SOURCE, text=True, cwd=cwd,
                               capture_output=True)
                self.assertEqual(marker.exists(), planted)

    def test_truncated_source_runs_nothing(self):
        lines = SOURCE.splitlines(keepends=True)
        cwd = tree(self)
        for cut in range(0, len(lines) - 1, max(1, len(lines) // 12)):
            with self.subTest(cut=cut):
                done = subprocess.run([sys.executable, "-I", "-", "--help"], input="".join(lines[:cut]), text=True,
                                      cwd=cwd, capture_output=True)
                self.assertNotIn("code-jig bootstrap", done.stdout)

    def test_full_source_runs(self):
        done = subprocess.run([sys.executable, "-I", "-", "--help"], input=SOURCE, text=True, capture_output=True)
        self.assertEqual(done.returncode, 0, done.stderr)
        self.assertIn("code-jig bootstrap", done.stdout)


class RefusesWithoutGit(unittest.TestCase):
    def test_bootstrap_refuses_without_git_before_writing(self):
        root = tree(self)
        data, bins = root / "data", root / "bin"
        out, err = io.StringIO(), io.StringIO()
        with mock.patch("shutil.which", return_value=None), \
                contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = bootstrap.main(["--data-dir", str(data), "--bin-dir", str(bins)])
        self.assertEqual(code, 2)
        self.assertIn("missing requirement: git (", err.getvalue())
        self.assertFalse(data.exists())
        self.assertFalse(bins.exists())

    def test_help_works_without_git(self):
        with mock.patch("shutil.which", return_value=None), contextlib.redirect_stdout(io.StringIO()), \
                self.assertRaises(SystemExit) as cm:
            bootstrap.main(["--help"])
        self.assertEqual(cm.exception.code, 0)

    def test_git_line_matches_install(self):
        with mock.patch("shutil.which", return_value=None):
            self.assertEqual(bootstrap.missing_requirements()[-1], install.missing_requirements()[-1])


class OldPythonSafe(unittest.TestCase):
    def test_no_annotations_or_match_before_the_version_check(self):
        tree_ = ast.parse(SOURCE, feature_version=(3, 8))
        bad = []
        for node in ast.walk(tree_):
            if isinstance(node, ast.FunctionDef):
                args = node.args.posonlyargs + node.args.args + node.args.kwonlyargs
                if node.returns or any(a.annotation for a in args):
                    bad.append(node.name)
            elif isinstance(node, ast.AnnAssign) or type(node).__name__ == "Match":
                bad.append(type(node).__name__)
        self.assertEqual(bad, [])
