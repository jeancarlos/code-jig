import os
import sys
import time
from pathlib import Path

from harness import paths
from harness.overlay import Overlay, load

MARKER = "<!-- generated by codex-harness: edit the core or the overlay, not this file -->\n"
BOM = b"\xef\xbb\xbf"


def render_agents(core: Path, overlay_root: Path) -> str:
    parts = [(core / "core" / "AGENTS.core.md").read_text(encoding="utf-8")]
    extra = overlay_root / "AGENTS.overlay.md"
    if extra.is_file():
        parts.append(extra.read_text(encoding="utf-8"))
    return MARKER + "\n".join(p.rstrip("\n") + "\n" for p in parts)


def _is_generated(path: Path) -> bool:
    head = path.read_bytes()[: len(BOM) + len(MARKER.encode())]
    return head.removeprefix(BOM).startswith(MARKER.encode())


def write_generated(path: Path, text: str) -> Path | None:
    backup = None
    if path.exists() and not _is_generated(path):
        backup = path.with_name(f"{path.name}.bak-{time.strftime('%Y%m%d-%H%M%S')}")
        path.replace(backup)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8", newline="\n")
    os.replace(tmp, path)
    return backup


def run(core: Path, ov: Overlay, home: Path) -> list[str]:
    target = home / "AGENTS.md"
    backup = write_generated(target, render_agents(core, ov.root))
    lines = [f"wrote {target}"]
    if backup:
        lines.append(f"moved your previous file to {backup}")
    return lines


def cli(args) -> int:
    try:
        ov = load(paths.overlay_dir(args.overlay))
    except ValueError as e:
        print(f"harness: {e}", file=sys.stderr)
        return 2
    for line in run(paths.CORE, ov, paths.codex_home(args.codex_home)):
        print(line)
    return 0
