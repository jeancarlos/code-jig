import hashlib
import json
import shlex
import shutil
import sys
import time
from pathlib import Path

from harness.atomicwrite import atomic_write
from harness import paths, tiers
from harness.overlay import Overlay, load

MARKER_BODY = "generated by codex-harness sha256:"
MARKER_NOTE = " : edit the core or the overlay, not this file"
STYLES = {"md": ("<!-- ", " -->"), "hash": ("# ", "")}
MARKER_PREFIX = STYLES["md"][0] + MARKER_BODY
BOM = b"\xef\xbb\xbf"


def stamp(body: str, style: str = "md") -> str:
    head, tail = STYLES[style]
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    return f"{head}{MARKER_BODY}{digest}{MARKER_NOTE}{tail}\n{body}"


def render_agents(core: Path, overlay_root: Path) -> str:
    parts = [(core / "core" / "AGENTS.core.md").read_text(encoding="utf-8-sig")]
    extra = overlay_root / "AGENTS.overlay.md"
    if extra.is_file():
        parts.append(extra.read_text(encoding="utf-8-sig"))
    index = overlay_root / "knowledge" / "INDEX.md"
    if index.is_file():
        parts.append(f"## Knowledge\n\nThis machine keeps one fact per file in {index.parent}. "
                     f"Read {index} when a task touches a tool, service or convention it may cover.\n")
    return stamp("\n".join(p.rstrip("\n") + "\n" for p in parts))


def is_generated(path: Path) -> bool:
    data = path.read_bytes().removeprefix(BOM)
    first, _, body = data.partition(b"\n")
    for head, tail in STYLES.values():
        prefix, suffix = (head + MARKER_BODY).encode(), (MARKER_NOTE + tail).encode()
        if len(first) > len(prefix) + len(suffix) and first.startswith(prefix) and first.endswith(suffix):
            digest = first[len(prefix): len(first) - len(suffix)].decode("ascii", "replace")
            return hashlib.sha256(body).hexdigest() == digest
    return False


def _backup_name(path: Path) -> Path:
    backup = path.with_name(f"{path.name}.bak-{time.strftime('%Y%m%d-%H%M%S')}")
    n = 0
    while backup.exists() or backup.is_symlink():
        n += 1
        backup = path.with_name(f"{path.name}.bak-{time.strftime('%Y%m%d-%H%M%S')}-{n}")
    return backup


def write_generated(path: Path, text: str) -> Path | None:
    path.parent.mkdir(parents=True, exist_ok=True)
    backup = None
    if path.exists() and not is_generated(path):
        backup = _backup_name(path)
        shutil.copy2(path, backup)
    atomic_write(path, text.encode("utf-8"))
    return backup


HOOK_STATUS = "codex-harness collect"
CLAUDE_CODE_WATERMARK_STATUS = "codex-harness watermark"


def interpreter() -> str:
    return getattr(sys, "_base_executable", None) or sys.executable


def hook_commands(lib: Path, home: Path, python: str) -> tuple[str, str]:
    posix = f"PYTHONPATH={shlex.quote(str(lib))} {shlex.quote(python)} -P -s -m harness --codex-home {shlex.quote(str(home))} collect"
    windows = f'set "PYTHONPATH={lib}" && "{python}" -P -s -m harness --codex-home "{home}" collect'
    return posix, windows


def watermark_commands(lib: Path, python: str, agent: str) -> tuple[str, str]:
    posix = f"PYTHONPATH={shlex.quote(str(lib))} {shlex.quote(python)} -P -s -m harness hooks --hook-type {agent}"
    windows = f'set "PYTHONPATH={lib}" && "{python}" -P -s -m harness hooks --hook-type {agent}'
    return posix, windows


def claude_code_watermark_hook(lib: Path, python: str) -> str:
    return watermark_commands(lib, python, "claude-code")[0]


def _without_status(groups: list, status: str) -> list:
    return [g for g in groups if not (isinstance(g, dict) and any(
        isinstance(h, dict) and h.get("statusMessage") == status for h in g.get("hooks") or []))]


def valid_hook_groups(groups) -> bool:
    return isinstance(groups, list) and all(
        isinstance(g, dict) and isinstance(g.get("hooks", []), list)
        and all(isinstance(h, dict) for h in g.get("hooks", [])) for g in groups)


def merged_hooks(path: Path, posix: str, windows: str, watermark: tuple[str, str] | None = None) -> str:
    try:
        data = json.loads(path.read_text(encoding="utf-8-sig")) if path.is_file() else {"hooks": {}}
    except (OSError, ValueError) as e:
        raise ValueError(f"{path}: {e}") from e
    hooks = data.setdefault("hooks", {}) if isinstance(data, dict) else None
    if not isinstance(hooks, dict) or not valid_hook_groups(hooks.setdefault("Stop", [])):
        raise ValueError(f'{path}: expected {{"hooks": {{"Stop": [...]}}}}')
    hooks["Stop"] = _without_status(hooks["Stop"], HOOK_STATUS)
    hooks["Stop"].append({"hooks": [{"type": "command", "command": posix, "commandWindows": windows,
                                     "timeout": 60, "statusMessage": HOOK_STATUS}]})
    if watermark is not None:
        post = hooks.setdefault("PostToolUse", [])
        if not isinstance(post, list):
            raise ValueError(f'{path}: expected {{"hooks": {{"PostToolUse": [...]}}}}')
        hooks["PostToolUse"] = _without_status(post, CLAUDE_CODE_WATERMARK_STATUS)
        hooks["PostToolUse"].append({"hooks": [{"type": "command", "command": watermark[0],
                                                "commandWindows": watermark[1], "timeout": 10,
                                                "statusMessage": CLAUDE_CODE_WATERMARK_STATUS}]})
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def write_merged(path: Path, text: str) -> Path | None:
    if path.is_file() and path.read_bytes() == text.encode("utf-8"):
        return None
    path.parent.mkdir(parents=True, exist_ok=True)
    backup = None
    if path.exists():
        backup = _backup_name(path)
        shutil.copy2(path, backup)
    atomic_write(path, text.encode("utf-8"))
    return backup


def merged_claude_code_hooks(path: Path, command: str) -> str:
    try:
        data = json.loads(path.read_text(encoding="utf-8-sig")) if path.is_file() else {"hooks": {}}
    except (OSError, ValueError) as e:
        raise ValueError(f"{path}: {e}") from e
    hooks = data.setdefault("hooks", {}) if isinstance(data, dict) else None
    if not isinstance(hooks, dict) or not valid_hook_groups(hooks.setdefault("PostToolUse", [])):
        raise ValueError(f'{path}: expected {{"hooks": {{"PostToolUse": [...]}}}}')
    hooks["PostToolUse"] = _without_status(hooks["PostToolUse"], CLAUDE_CODE_WATERMARK_STATUS)
    hooks["PostToolUse"].append({
        "matcher": "Write|Edit|MultiEdit|NotebookEdit",
        "hooks": [{"type": "command", "command": command, "timeout": 10,
                   "statusMessage": CLAUDE_CODE_WATERMARK_STATUS}],
    })
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


RULES_PREFIX = "codex-harness-"


def rule_files(overlay_root: Path) -> dict[str, str]:
    src = overlay_root / "rules"
    if not src.is_dir():
        return {}
    return {f"{RULES_PREFIX}{p.stem}.rules": stamp(p.read_text(encoding="utf-8-sig"), "hash")
            for p in sorted(src.glob("*.rules"))}


def prune_rules(rules_dir: Path, keep: set[str]) -> list[str]:
    lines = []
    for f in sorted(rules_dir.glob(f"{RULES_PREFIX}*.rules")) if rules_dir.is_dir() else []:
        if f.name in keep:
            continue
        if is_generated(f):
            f.unlink()
            lines.append(f"removed {f}: no longer in the overlay")
        else:
            lines.append(f"warning: left {f}: edited by hand, Codex still loads it")
    return lines


SKILL_SIDECAR = ".codex-harness"


def _skill_dirs(root: Path) -> dict[str, Path]:
    return {p.parent.name: p.parent for p in sorted(root.glob("*/SKILL.md"))} if root.is_dir() else {}


def skill_sources(core: Path, overlay_root: Path) -> dict[str, Path]:
    core_skills, ov_skills = _skill_dirs(core / "skills"), _skill_dirs(overlay_root / "skills")
    clash = sorted(set(core_skills) & set(ov_skills))
    if clash:
        raise ValueError(f"{overlay_root / 'skills'}: {', '.join(clash)} already in {core / 'skills'}; rename the overlay skill")
    return {**core_skills, **ov_skills}


def tree_digest(src: Path) -> str:
    h = hashlib.sha256()
    for f in sorted(p for p in src.rglob("*") if p.is_file() and p.name != SKILL_SIDECAR and "__pycache__" not in p.parts):
        h.update(f.relative_to(src).as_posix().encode() + b"\0" + f.read_bytes() + b"\0")
    return h.hexdigest()


def _own_skill(d: Path) -> bool:
    side = d / SKILL_SIDECAR
    return side.is_file() and side.read_text(encoding="utf-8").strip() == tree_digest(d)


def install_skills(sources: dict[str, Path], dest: Path) -> list[str]:
    lines = []
    dest.mkdir(parents=True, exist_ok=True)
    for name, src in sources.items():
        target = dest / name
        if target.exists() and not _own_skill(target):
            backups = dest.parent / "skills-backup"
            backups.mkdir(parents=True, exist_ok=True)
            backup = _backup_name(backups / name)
            target.replace(backup)
            lines.append(f"moved your previous {target} to {backup}")
        elif target.exists():
            shutil.rmtree(target)
        shutil.copytree(src, target, ignore=shutil.ignore_patterns("__pycache__", SKILL_SIDECAR))
        (target / SKILL_SIDECAR).write_text(tree_digest(target) + "\n", encoding="utf-8", newline="\n")
        lines.append(f"wrote {target}")
    for d in sorted(p for p in dest.iterdir() if p.is_dir() and p.name not in sources and (p / SKILL_SIDECAR).is_file()):
        if _own_skill(d):
            shutil.rmtree(d)
            lines.append(f"removed {d}: no longer in the core or overlay")
        else:
            lines.append(f"warning: left {d}: edited by hand, Codex still loads it")
    return lines


def render_profile(tier: tiers.Tier, policy: str) -> str:
    return stamp(tiers.profile_body(tier, policy), "hash")


def plan(core: Path, ov: Overlay, home: Path, claude_code_settings: Path | None = None) -> list[tuple[Path, str]]:
    skill_sources(core, ov.root)
    policy = tiers.extra_policy(ov.root)
    outputs = [(home / "AGENTS.md", render_agents(core, ov.root))]
    outputs += [(home / f"{t.name}.config.toml", render_profile(t, policy)) for t in tiers.load(core, ov.root)]
    outputs += [(home / "rules" / name, text) for name, text in rule_files(ov.root).items()]
    lib = home / "codex-harness" / "lib"
    outputs += [(lib / "harness" / p.name, stamp(p.read_text(encoding="utf-8"), "hash")) for p in sorted((core / "harness").glob("*.py"))]
    outputs.append((home / "hooks.json", merged_hooks(home / "hooks.json", *hook_commands(lib, home, interpreter()),
                                                      watermark=watermark_commands(lib, interpreter(), "codex"))))
    if claude_code_settings and claude_code_settings.is_file():
        outputs.append((claude_code_settings, merged_claude_code_hooks(claude_code_settings, claude_code_watermark_hook(lib, interpreter()))))
    return outputs


def run(core: Path, ov: Overlay, home: Path) -> list[str]:
    lines = []
    claude_settings = paths.claude_code_settings()
    for target, text in plan(core, ov, home, claude_settings):
        backup = (write_merged if target.name in ("hooks.json", "settings.json") else write_generated)(target, text)
        lines.append(f"wrote {target}")
        if backup:
            lines.append(f"moved your previous file to {backup}")
    lines += prune_rules(home / "rules", set(rule_files(ov.root)))
    lines += install_skills(skill_sources(core, ov.root), paths.agents_skills())
    override = home / "AGENTS.override.md"
    if override.is_file() and override.stat().st_size > 0:
        lines.append(f"warning: {override} exists and Codex loads it instead of {home / 'AGENTS.md'}")
    return lines


def cli(args) -> int:
    try:
        lines = run(paths.CORE, load(paths.overlay_dir(args.overlay)), paths.codex_home(args.codex_home))
    except ValueError as e:
        print(f"harness: {e}", file=sys.stderr)
        return 2
    for line in lines:
        print(line)
    return 0
