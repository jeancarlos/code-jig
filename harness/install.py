import hashlib
import os
import sys
import time
from pathlib import Path

from harness import paths
from harness.overlay import Overlay, load

MARKER_BODY = "generated by codex-harness sha256:"
MARKER_NOTE = " : edit the core or the overlay, not this file"
STYLES = {"md": ("<!-- ", " -->"), "hash": ("# ", "")}
MARKER_PREFIX = STYLES["md"][0] + MARKER_BODY
BOM = b"\xef\xbb\xbf"


def stamp(body: str, style: str = "md") -> str:
    head, tail = STYLES[style]
    digest = hashlib.sha256(body.encode("utf-8")).hexdigest()
    return f"{head}{MARKER_BODY}{digest}{MARKER_NOTE}{tail}\n{body}"


def render_agents(core: Path, overlay_root: Path) -> str:
    parts = [(core / "core" / "AGENTS.core.md").read_text(encoding="utf-8-sig")]
    extra = overlay_root / "AGENTS.overlay.md"
    if extra.is_file():
        parts.append(extra.read_text(encoding="utf-8-sig"))
    return stamp("\n".join(p.rstrip("\n") + "\n" for p in parts))


def is_generated(path: Path) -> bool:
    data = path.read_bytes().removeprefix(BOM)
    first, _, body = data.partition(b"\n")
    for head, tail in STYLES.values():
        prefix, suffix = (head + MARKER_BODY).encode(), (MARKER_NOTE + tail).encode()
        if len(first) > len(prefix) + len(suffix) and first.startswith(prefix) and first.endswith(suffix):
            digest = first[len(prefix): len(first) - len(suffix)].decode("ascii", "replace")
            return hashlib.sha256(body).hexdigest() == digest
    return False


def write_generated(path: Path, text: str) -> Path | None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8", newline="\n")
    backup = None
    if path.exists() and not is_generated(path):
        backup = path.with_name(f"{path.name}.bak-{time.strftime('%Y%m%d-%H%M%S')}")
        n = 0
        while backup.exists():
            n += 1
            backup = path.with_name(f"{path.name}.bak-{time.strftime('%Y%m%d-%H%M%S')}-{n}")
        path.replace(backup)
    os.replace(tmp, path)
    return backup


def run(core: Path, ov: Overlay, home: Path) -> list[str]:
    target = home / "AGENTS.md"
    backup = write_generated(target, render_agents(core, ov.root))
    lines = [f"wrote {target}"]
    if backup:
        lines.append(f"moved your previous file to {backup}")
    override = home / "AGENTS.override.md"
    if override.is_file() and override.stat().st_size > 0:
        lines.append(f"warning: {override} exists and Codex loads it instead of {target}")
    return lines


def cli(args) -> int:
    try:
        ov = load(paths.overlay_dir(args.overlay))
    except ValueError as e:
        print(f"harness: {e}", file=sys.stderr)
        return 2
    for line in run(paths.CORE, ov, paths.codex_home(args.codex_home)):
        print(line)
    return 0
